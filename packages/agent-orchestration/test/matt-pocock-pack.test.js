import { afterEach, describe, expect, it } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import YAML from 'yaml';
import packBuilder from '../../../build/matt-pocock.js';

const { createPack, writePack, SOURCE } = packBuilder;
const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');
const temporary = [];
const temp = () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'arcw-matt-pack-'));
  temporary.push(root);
  return root;
};
const put = (root, rel, content) => {
  const dest = path.join(root, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content);
};
afterEach(() => temporary.splice(0).forEach((root) => fs.rmSync(root, { recursive: true, force: true })));

function fixture() {
  const root = temp();
  const source = {
    revision: '1'.repeat(40), maintenance: 'arcwright-local',
    skills: [{ name: 'tdd', installedName: 'matt-pocock-tdd', source: 'skills/engineering/tdd' }],
  };
  put(root, `${SOURCE}/SOURCE.json`, JSON.stringify(source));
  for (const name of ['matt-pocock', 'matt-pocock-tdd']) {
    put(root, `.agents/skills/${name}/LICENSE`, 'MIT fixture license\n');
    put(root, `.agents/skills/${name}/SKILL.md`, `---\nname: ${name}\ndescription: Fixture skill\n---\nLocal instructions.\n`);
  }
  put(root, '.agents/skills/matt-pocock-tdd/tests.md', 'Local reference\n');
  return { root, source };
}

describe('Arcwright local engineering and productivity pack', () => {
  it('ships all local skills, resources, invocation policy, licenses, and origin records', () => {
    const pack = createPack(REPO_ROOT);
    const source = JSON.parse(pack.output.get(`${SOURCE}/SOURCE.json`));
    const license = fs.readFileSync(path.join(REPO_ROOT, SOURCE, 'LICENSE'));
    expect(source.maintenance).toBe('arcwright-local');
    expect(source.revision).toMatch(/^[a-f0-9]{40}$/);
    expect(Object.keys(source.sourceFiles).length).toBeGreaterThan(27);
    expect(pack.count).toBe(27);
    for (const skill of source.skills) {
      const base = `.agents/skills/${skill.installedName}`;
      expect(pack.output.get(`${base}/SKILL.md`).toString()).toContain(`name: ${skill.installedName}\n`);
      expect(pack.output.get(`${base}/LICENSE`)).toEqual(license);
      const metadata = YAML.parse(pack.output.get(`${base}/agents/openai.yaml`).toString());
      expect(metadata.policy?.allow_implicit_invocation).not.toBe(false);
      expect(pack.output.get(`${base}/SKILL.md`).toString()).not.toMatch(/^disable-model-invocation:\s*true/m);
    }
    expect(pack.output.get('.agents/skills/matt-pocock-grill-with-docs/SKILL.md').toString()).toContain('"matt-pocock-grilling" and "matt-pocock-domain-modeling"');
    const wayfinder = pack.output.get('.agents/skills/matt-pocock-wayfinder/SKILL.md').toString();
    expect(wayfinder).toContain('one of `research`, `prototype`, `grilling`, `task`');
    expect(wayfinder).toContain('For each `research` ticket');
    expect(wayfinder).toContain('Skill tool with "matt-pocock-research"');
    expect(pack.output.get('.agents/skills/matt-pocock-triage/SKILL.md').toString()).not.toContain('generated by AI');
    expect(pack.output.get('.agents/skills/matt-pocock-wizard/template.sh').toString()).not.toContain('Generated by');
    expect(pack.output.has('.agents/skills/matt-pocock-tdd/tests.md')).toBe(true);
    expect(pack.output.has('.agents/skills/matt-pocock-pr/CREDITS.md')).toBe(true);
    expect([...pack.output.keys()].some(rel => /loop-me|git-guardrails-claude-code|\.local-install/.test(rel))).toBe(false);
    expect(JSON.parse(pack.output.get('.kiro/agents/matt-pocock.json')).includeMcpJson).toBe(true);
    expect(YAML.parse(pack.output.get(`${SOURCE}/agents/openai.yaml`).toString()).policy.allow_implicit_invocation).toBe(true);
    expect(pack.output.get(`${SOURCE}/INTEGRATION.md`).toString()).toContain('_arcwright/_memory/skill-runs/');
  });

  it('packages our edits without Git, an upstream checkout, or regeneration', () => {
    const { root } = fixture();
    const rel = '.agents/skills/matt-pocock-tdd/tests.md';
    put(root, rel, 'Our revised reference\n');
    const command = '.claude/commands/matt-pocock-tdd.md';
    put(root, command, '---\ndescription: Our custom launcher\n---\nCustom task routing.\n');
    const pack = createPack(root);
    expect(fs.existsSync(path.join(root, '.git'))).toBe(false);
    expect(fs.existsSync(path.join(root, 'vendor'))).toBe(false);
    expect(pack.output.get(rel).toString()).toBe('Our revised reference\n');
    expect(pack.output.get(command).toString()).toContain('Custom task routing.');
    const dest = temp();
    writePack(pack, dest);
    expect(fs.readFileSync(path.join(dest, rel), 'utf8')).toBe('Our revised reference\n');
  });

  it('rejects missing resources, mismatched skill names, and unsafe or duplicate catalog entries', () => {
    const { root, source } = fixture();
    const skill = '.agents/skills/matt-pocock-tdd/SKILL.md';
    put(root, skill, '---\nname: unrelated\n---\n');
    expect(() => createPack(root)).toThrow('does not match directory');
    put(root, skill, '---\nname: matt-pocock-tdd\n---\n');
    fs.unlinkSync(path.join(root, '.agents/skills/matt-pocock-tdd/LICENSE'));
    expect(() => createPack(root)).toThrow(/LICENSE/);
    source.skills.push({ installedName: '../outside' });
    put(root, `${SOURCE}/SOURCE.json`, JSON.stringify(source));
    expect(() => createPack(root)).toThrow('Invalid or duplicate');
    source.skills[1].installedName = 'matt-pocock-tdd';
    put(root, `${SOURCE}/SOURCE.json`, JSON.stringify(source));
    expect(() => createPack(root)).toThrow('Invalid or duplicate');
  });

  it.skipIf(process.platform === 'win32')('refuses symlinked skill resources and symlinked output directories', () => {
    const { root } = fixture();
    const outside = temp();
    put(outside, 'secret.md', 'outside data');
    const link = path.join(root, '.agents/skills/matt-pocock-tdd/escape.md');
    fs.symlinkSync(path.join(outside, 'secret.md'), link);
    expect(() => createPack(root)).toThrow('Refusing symlinked build input');
    fs.unlinkSync(link);
    const pack = createPack(root);
    const dest = temp();
    fs.symlinkSync(outside, path.join(dest, '.agents'));
    expect(() => writePack(pack, dest)).toThrow('Refusing symlinked build input');
    expect(fs.readdirSync(outside)).toEqual(['secret.md']);
  });

  it('ignores retired upstream checkouts and importer state', () => {
    const { root } = fixture();
    put(root, 'vendor/mattpocock-skills/skills/engineering/tdd/SKILL.md', 'obsolete upstream instructions');
    put(root, `${SOURCE}/.local-install.json`, JSON.stringify({ '../outside': 'obsolete manifest' }));
    put(root, '.agents/skills/matt-pocock-tdd/__pycache__/local.pyc', 'cache');
    const pack = createPack(root);
    expect(pack.output.get('.agents/skills/matt-pocock-tdd/SKILL.md').toString()).toContain('Local instructions.');
    expect([...pack.output.keys()].some(rel => /vendor|\.local-install|__pycache__/.test(rel))).toBe(false);
  });

  it('local maintenance creates wrappers without rewriting or deleting skill source', () => {
    const { root } = fixture();
    const pack = createPack(root);
    const changed = '.agents/skills/matt-pocock-tdd/SKILL.md';
    const stale = '.agents/skills/matt-pocock-tdd/tests.md';
    fs.appendFileSync(path.join(root, changed), 'Our latest changes\n');
    pack.output.delete(stale);
    writePack(pack, root, { local: true });
    writePack(pack, root, { local: true });
    expect(fs.readFileSync(path.join(root, changed), 'utf8')).toContain('Our latest changes');
    expect(fs.existsSync(path.join(root, stale))).toBe(true);
    expect(fs.existsSync(path.join(root, '.claude/commands/matt-pocock-tdd.md'))).toBe(true);
    expect(fs.existsSync(path.join(root, '.kiro'))).toBe(false);
    expect(fs.existsSync(path.join(root, SOURCE, '.local-install.json'))).toBe(false);
  });

  it('rejects unregistered local skills and protects destination edits before writing', () => {
    const { root } = fixture();
    const dest = temp();
    const pack = createPack(root);
    put(dest, '.agents/skills/matt-pocock-tdd/tests.md', 'Destination user edit');
    expect(() => writePack(pack, dest)).toThrow('Refusing to overwrite');
    expect(fs.existsSync(path.join(dest, SOURCE, 'SKILL.md'))).toBe(false);
    put(root, '.agents/skills/matt-pocock-new/SKILL.md', 'new skill');
    expect(() => createPack(root)).toThrow('missing from the skill-pack catalog');
  });


});
